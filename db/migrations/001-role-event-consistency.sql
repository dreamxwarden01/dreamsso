-- Upgrade the event channel without rewriting application identities or assignments.
ALTER TABLE event_outbox ADD COLUMN IF NOT EXISTS sequence bigint GENERATED BY DEFAULT AS IDENTITY;
ALTER TABLE event_outbox ADD COLUMN IF NOT EXISTS last_error_code text;
ALTER TABLE event_outbox ADD COLUMN IF NOT EXISTS legacy_redis_member text;
ALTER TABLE event_outbox ADD COLUMN IF NOT EXISTS legacy_redis_score double precision;
CREATE UNIQUE INDEX IF NOT EXISTS event_outbox_sequence ON event_outbox(sequence);
CREATE INDEX IF NOT EXISTS event_outbox_client_pending ON event_outbox(target_client_id,sequence) WHERE status='pending';
CREATE TABLE IF NOT EXISTS event_destinations (
    client_id text PRIMARY KEY REFERENCES oauth_clients(client_id) ON DELETE CASCADE,
    lease_token uuid,lease_until timestamptz,next_attempt_at timestamptz NOT NULL DEFAULT now(),
    failures integer NOT NULL DEFAULT 0 CHECK(failures>=0),
    CHECK((lease_token IS NULL)=(lease_until IS NULL))
);
ALTER TABLE processed_events ADD COLUMN IF NOT EXISTS event_type text;
ALTER TABLE processed_events ADD COLUMN IF NOT EXISTS payload_digest bytea CHECK(payload_digest IS NULL OR octet_length(payload_digest)=32);
DO $$ BEGIN
  IF EXISTS(SELECT 1 FROM pg_constraint WHERE conrelid='processed_events'::regclass AND contype='p'
    AND pg_get_constraintdef(oid)<>'PRIMARY KEY (source, id)') THEN
    ALTER TABLE processed_events DROP CONSTRAINT processed_events_pkey;
    ALTER TABLE processed_events ADD PRIMARY KEY(source,id);
  END IF;
END $$;
CREATE TABLE IF NOT EXISTS app_role_sync_state (
    client_id text PRIMARY KEY REFERENCES oauth_clients(client_id) ON DELETE CASCADE,
    catalog_mode text NOT NULL DEFAULT 'legacy' CHECK(catalog_mode IN('legacy','revisioned')),
    catalog_epoch uuid,
    catalog_revision bigint,
    catalog_digest bytea CHECK(catalog_digest IS NULL OR octet_length(catalog_digest)=32),
    last_sync_iat bigint NOT NULL DEFAULT 0,
    authority_epoch uuid NOT NULL DEFAULT gen_random_uuid(),
    authority_revision bigint NOT NULL DEFAULT 0 CHECK(authority_revision>=0),
    CHECK ((catalog_mode='legacy' AND catalog_epoch IS NULL AND catalog_revision IS NULL)
        OR (catalog_mode='revisioned' AND catalog_epoch IS NOT NULL AND catalog_revision IS NOT NULL AND catalog_revision>0))
);
CREATE TABLE IF NOT EXISTS app_role_effective (
    client_id text NOT NULL REFERENCES oauth_clients(client_id) ON DELETE CASCADE,
    user_sub uuid NOT NULL REFERENCES identities(sub) ON DELETE CASCADE,
    role_id integer,
    managed boolean NOT NULL,
    authority_revision bigint NOT NULL DEFAULT 0 CHECK(authority_revision>=0),
    PRIMARY KEY(client_id,user_sub)
);

-- Baseline already-managed clients without inventing historical notifications.
INSERT INTO app_role_sync_state(client_id,last_sync_iat)
SELECT client_id,last_sync_iat FROM app_role_catalogs ON CONFLICT(client_id) DO NOTHING;
WITH effective AS(
 SELECT cat.client_id,i.sub,CASE WHEN ov.user_sub IS NOT NULL THEN ov.app_role_id
   WHEN od.role_slug IS NOT NULL THEN od.app_role_id ELSE cat.default_role_id END AS raw_role
 FROM identities i CROSS JOIN app_role_catalogs cat
 LEFT JOIN user_app_role_overrides ov ON ov.user_sub=i.sub AND ov.client_id=cat.client_id
 LEFT JOIN user_org_roles ur ON ur.user_sub=i.sub
 LEFT JOIN org_role_app_defaults od ON od.role_slug=ur.org_role_slug AND od.client_id=cat.client_id
 WHERE i.deleted_at IS NULL)
INSERT INTO app_role_effective(client_id,user_sub,role_id,managed,authority_revision)
SELECT e.client_id,e.sub,r.role_id,true,s.authority_revision FROM effective e
JOIN app_role_sync_state s USING(client_id)
LEFT JOIN app_roles r ON r.client_id=e.client_id AND r.role_id=e.raw_role
ON CONFLICT(client_id,user_sub) DO NOTHING;
-- Ask existing peers for fresh state once; this cannot reconstruct lost history.
INSERT INTO event_outbox(kind,target_client_id,payload,status)
SELECT 'roles.sync_request',c.client_id,'{"reason":"role_event_consistency_upgrade"}'::jsonb,'pending'
FROM oauth_clients c JOIN app_role_catalogs cat USING(client_id)
WHERE c.disabled_at IS NULL AND c.events_uri IS NOT NULL
  AND NOT EXISTS(SELECT 1 FROM event_outbox e WHERE e.target_client_id=c.client_id
    AND e.kind='roles.sync_request' AND e.payload->>'reason'='role_event_consistency_upgrade');
INSERT INTO event_destinations(client_id)
SELECT DISTINCT target_client_id FROM event_outbox WHERE status='pending' AND target_client_id IS NOT NULL
ON CONFLICT(client_id) DO NOTHING;
